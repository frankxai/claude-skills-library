#!/usr/bin/env node
/**
 * install-any-agent.mjs — one install plan per agent harness, from one manifest.
 *
 *   node scripts/install-any-agent.mjs --list
 *   node scripts/install-any-agent.mjs --harness hermes --json
 *   node scripts/install-any-agent.mjs --all --json
 *   node scripts/install-any-agent.mjs --all --verify
 *
 * This is a PLAN GENERATOR. It never writes a skill, a junction, a stub into a home directory,
 * global configuration, or an install receipt. Dry run is the only mode. Stable exit codes:
 *   0 pass | 2 unknown harness | 3 missing adapter or marker | 4 unsafe absolute path |
 *   5 invalid manifest | 6 pack root missing | 7 bad arguments.
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '..')
const RUNTIMES = join(REPO, 'runtimes')
const MANIFEST = join(RUNTIMES, 'harnesses.json')
const ABS_PATH = /(?:[A-Za-z]:\\[Uu]sers|[A-Za-z]:\/Users|\/c\/Users|\/Users\/|\/home\/)/
const MARKER = '<!-- generated by scripts/gen-harness-adapters.mjs'

const args = process.argv.slice(2)
const valueOf = (name) => {
  const i = args.indexOf(name)
  return i !== -1 && i + 1 < args.length ? args[i + 1] : null
}
const has = (name) => args.includes(name)
const json = has('--json')
const verify = has('--verify')
const all = has('--all')
const one = valueOf('--harness')

if (has('--list') && (verify || json || all || one)) {
  console.error('install-any-agent: --list takes no other mode flag')
  process.exit(7)
}
if (!has('--list') && !verify && !json && !all && !one) {
  console.error('install-any-agent: pass --list, --harness <id>, --all, --json or --verify')
  process.exit(7)
}

let manifest
try {
  manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
} catch (e) {
  console.error(`install-any-agent: cannot read manifest: ${e.message}`)
  process.exit(5)
}
if (manifest.schema !== 'agent-harness-manifest.v1' || !Array.isArray(manifest.harnesses)) {
  console.error('install-any-agent: invalid manifest schema')
  process.exit(5)
}
const packRoot = manifest.packRoot
const packRootExists = existsSync(join(REPO, packRoot))
if (!packRootExists) {
  console.error(`install-any-agent: pack root ${packRoot} is missing`)
  process.exit(6)
}

const byId = new Map(manifest.harnesses.map((h) => [h.id, h]))
if (one && !byId.has(one)) {
  console.error(`install-any-agent: unknown harness ${one}`)
  process.exit(2)
}
const selected = one ? [byId.get(one)] : all || verify ? manifest.harnesses : manifest.harnesses

if (has('--list')) {
  if (json) console.log(JSON.stringify(manifest.harnesses.map((h) => ({ id: h.id, label: h.label, kind: h.kind, existingAdapter: h.existingAdapter })), null, 2))
  else for (const h of manifest.harnesses) console.log(`${h.id.padEnd(18)} ${h.kind.padEnd(14)} ${h.label}`)
  process.exit(0)
}

function planFor(h) {
  const adapterPath = `runtimes/${h.id}.md`
  const full = join(REPO, adapterPath)
  const adapterExists = existsSync(full)
  const safe = !ABS_PATH.test(h.discovery) && !ABS_PATH.test(h.install) && !ABS_PATH.test(h.evidence)
  return {
    id: h.id,
    label: h.label,
    kind: h.kind,
    skillFormat: h.skillFormat,
    discovery: h.discovery,
    install: h.install,
    configRepo: h.configRepo,
    adapterPath,
    adapterExists,
    safe,
    sourced: !String(h.discovery).startsWith('[OPEN]') && !String(h.install).startsWith('[OPEN]'),
    repoGap: h.repoGap ?? null,
    steps: [
      `Read ${adapterPath}`,
      `Confirm the pack root ${packRoot}/<skill>/ contains SKILL.md and its relative references`,
      'Project the whole pack root; do not copy a single SKILL.md out of it',
      h.id === 'hermes'
        ? 'Add the pack root as an exact YAML list item under skills.external_dirs'
        : `Place or point at the discovery path: ${h.discovery}`,
      'Verify the harness loads the skill from its own discovery path',
      'Only a separate authorized live install writes a receipt under queen/reports/',
    ],
  }
}

const plans = selected.map(planFor)
const sourcedCount = manifest.harnesses.filter((h) => !String(h.discovery).startsWith('[OPEN]') && !String(h.install).startsWith('[OPEN]')).length
// A row with no explicit pathState is open, never verified. Proof is required for "verified".
const stateCount = (state) => manifest.harnesses.filter((h) => (h.pathState || 'open') === state).length
const checks = {
  manifest: 'PASS',
  packRoot: 'PASS',
  adaptersPresent: 'PASS',
  generatedMarkers: 'PASS',
  noAbsolutePaths: 'PASS',
  docsNoAbsolutePaths: 'PASS',
  sourcedSurfaces: `${sourcedCount}/${manifest.harnesses.length}`,
  openSurfaces: manifest.harnesses.length - sourcedCount,
  verified: stateCount('verified'),
  documented: stateCount('documented'),
  open: stateCount('open'),
}
const faults = []
let exit = 0
const setExit = (code, message) => { if (code > exit) exit = code; faults.push(message) }

for (const h of manifest.harnesses) {
  if (h.pathState === 'verified' && (!h.probe || !h.probeDate)) {
    checks.manifest = 'FAIL'
    setExit(5, `verified harness ${h.id} has no probe evidence`)
  }
}

function walkMd(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walkMd(p))
    else if (entry.name.endsWith('.md')) out.push(p)
  }
  return out
}

for (const h of manifest.harnesses) {
  const full = join(REPO, 'runtimes', `${h.id}.md`)
  if (!existsSync(full)) { checks.adaptersPresent = 'FAIL'; setExit(3, `missing adapter ${full}`); continue }
  const text = readFileSync(full, 'utf8').replace(/^\uFEFF/, '')
  if (!h.existingAdapter && !text.startsWith(MARKER)) { checks.generatedMarkers = 'FAIL'; setExit(3, `missing marker ${full}`) }
  if (ABS_PATH.test(text)) { checks.noAbsolutePaths = 'FAIL'; setExit(4, `absolute path in ${full}`) }
}
for (const p of plans) if (!p.safe) { checks.noAbsolutePaths = 'FAIL'; setExit(4, `unsafe plan ${p.id}`) }
const docsDir = join(REPO, 'docs', 'products')
if (existsSync(docsDir)) {
  for (const p of walkMd(docsDir)) {
    if (ABS_PATH.test(readFileSync(p, 'utf8'))) { checks.docsNoAbsolutePaths = 'FAIL'; setExit(4, `absolute path in ${p}`) }
  }
}

const output = {
  schema: 'agent-install-plan.v1',
  generatedBy: 'scripts/install-any-agent.mjs',
  asOf: manifest.asOf,
  dryRun: true,
  writesNothing: true,
  packRoot,
  packRootExists,
  harnessCount: manifest.harnesses.length,
  sourcedHarnesses: sourcedCount,
  selected: plans.length,
  plans,
  verification: { ...checks, faults, exitCode: exit },
  exitCode: exit,
}

if (json) {
  console.log(JSON.stringify(output, null, 2))
} else if (verify) {
  for (const [k, v] of Object.entries(checks)) console.log(`${k}: ${v}`)
  console.log(`adapters: ${manifest.harnesses.length} | generated stubs: ${manifest.harnesses.filter((h) => !h.existingAdapter).length} | pack root: ${packRoot}`)
  console.log(`sourced surfaces: ${sourcedCount}/${manifest.harnesses.length} | ${manifest.harnesses.length - sourcedCount} open ([OPEN] discovery)`)
  console.log(`path states: verified ${checks.verified} | documented ${checks.documented} | open ${checks.open}`)
  if (faults.length) for (const f of faults) console.log(`fault: ${f}`)
  console.log(exit === 0 ? 'VERDICT: PASS' : `VERDICT: FAIL (exit ${exit})`)
} else {
  console.log(`# Install plans - ${plans.length} of ${manifest.harnesses.length} harnesses (dry run, writes nothing)`)
  console.log('')
  console.log('| Harness | Kind | Discovery | Adapter | Safe |')
  console.log('|---|---|---|---|---|')
  for (const p of plans) console.log(`| ${p.id} | ${p.kind} | ${p.discovery} | ${p.adapterExists ? 'yes' : 'NO'} | ${p.safe ? 'yes' : 'NO'} |`)
  console.log('')
  console.log(`Pack root: ${packRoot}. Generated by scripts/install-any-agent.mjs. No live install was performed.`)
}
process.exit(exit)
