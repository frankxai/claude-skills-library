#!/usr/bin/env node
/**
 * gen-harness-adapters.mjs — project one skill pack onto every agent harness.
 *
 *   node scripts/gen-harness-adapters.mjs --check   # dry run: no writes, exit 1 on drift
 *   node scripts/gen-harness-adapters.mjs --write   # write missing/outdated generated stubs
 *
 * One manifest (runtimes/harnesses.json) is the source of truth. Adapter docs are stubs that
 * point at the pack root free-skills/<skill>/; they never contain a second copy of a skill body.
 * The six pre-existing adapter docs are preserved untouched. Output is deterministic and
 * byte-idempotent: a second --check after --write reports no drift.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '..')
const RUNTIMES = join(REPO, 'runtimes')
const MANIFEST = join(RUNTIMES, 'harnesses.json')
const MARKER = '<!-- generated by scripts/gen-harness-adapters.mjs from runtimes/harnesses.json; do not hand-edit -->'
const ABS_PATH = /(?:[A-Za-z]:\\[Uu]sers|[A-Za-z]:\/Users|\/c\/Users|\/Users\/|\/home\/)/

let manifest
try {
  manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
} catch (e) {
  console.error(`gen-harness-adapters: cannot read manifest: ${e.message}`)
  process.exit(5)
}
if (manifest.schema !== 'agent-harness-manifest.v1' || !Array.isArray(manifest.harnesses)) {
  console.error('gen-harness-adapters: invalid manifest schema')
  process.exit(5)
}

function stubFor(h) {
  const lines = [
    MARKER,
    `# Importing skills into ${h.label}`,
    '',
    `Status: generated stub, ${manifest.asOf}. This is a discovery guide, not a live install. No skill`,
    'body is copied here and no global configuration was changed.',
    '',
    '## Source of truth',
    '',
    `The pack root is \`${manifest.packRoot}/<skill>/\`. It contains \`SKILL.md\` and any`,
    '`references/`, `scripts/` and `assets/` beside it. Adapters point at that root. Pack-relative',
    'references such as `../../references` keep working only when the whole pack root is projected,',
    'not when a single `SKILL.md` is copied out of it.',
    '',
    '## Discovery',
    '',
    h.discovery,
    '',
    '## Install plan (dry run only)',
    '',
    '```text',
    h.install,
    '```',
    '',
    'The canonical plan for this harness is emitted by:',
    '',
    '```text',
    `node scripts/install-any-agent.mjs --harness ${h.id} --json`,
    `node scripts/install-any-agent.mjs --harness ${h.id} --verify`,
    '```',
    '',
    '## Safety rules',
    '',
    `- Stubs only. ${manifest.policy.noOverwriteFullSkills ? 'A full skill body is never overwritten.' : ''}`,
    '- Detect Windows reparse points before any stub write. Never write through a junction into the pack source.',
    '- For Hermes mega-trees, add the pack root as an exact YAML list item under `skills.external_dirs`.',
    '  A substring match gives false positives on sibling paths.',
    '- Repository-distributed artifacts carry no operator-specific path. Private runtime stub paths',
    '  stay out of staging and publication.',
    '- Any live install writes a receipt under `queen/reports/harness-install-<date>.md`.',
    '',
    '## Verify',
    '',
    '```text',
    'node scripts/gen-harness-adapters.mjs --check',
    'node scripts/install-any-agent.mjs --all --verify',
    '```',
    '',
    '## Not done here',
    '',
    'No live install, no junction, no global config edit, no stub written into a home directory, and',
    'no receipt claiming an install happened. Those are separate authorized actions.',
    '',
    '## Evidence',
    '',
    h.evidence,
    ...(h.repoGap ? ['', `Repo gap: ${h.repoGap}`] : []),
    '',
  ]
  return lines.join('\n')
}

function readmeFor() {
  const rows = manifest.harnesses.map((h) =>
    `| ${h.label} | ${h.kind} | ${h.existingAdapter ? 'existing doc' : 'generated stub'} | [\`${h.id}.md\`](./${h.id}.md) |`
  )
  return [
    MARKER,
    '# Multi-runtime import guides',
    '',
    `Generated from [\`harnesses.json\`](./harnesses.json) by \`scripts/gen-harness-adapters.mjs\`.`,
    `As of ${manifest.asOf}: ${manifest.harnesses.length} harness surfaces, ${manifest.inventory.existingAdapters} pre-existing adapter docs.`,
    '',
    '| Runtime | Kind | Surface | Guide |',
    '|---|---|---|---|',
    ...rows,
    '',
    '## Start here',
    '',
    '```text',
    'node scripts/install-any-agent.mjs --all --json',
    'node scripts/install-any-agent.mjs --all --verify',
    'node scripts/gen-harness-adapters.mjs --check',
    '```',
    '',
    '## Pack integrity',
    '',
    `- The pack root is \`${manifest.packRoot}/\`. Adapters are stubs that point at it.`,
    '- Never copy only `skills/<name>/` out of a pack. Pack-relative references break.',
    '- Stubs discover; the pack path stays the source of truth.',
    '- Windows junctions are not symlinks. Detect reparse points before writing a stub.',
    '- No overwrite of a full skill body. A dry run creates no surfaces, config edits or receipts.',
    '',
    'For the historical overview and the MCP bridge rationale, see top-level',
    '[`MULTI_RUNTIME.md`](../MULTI_RUNTIME.md) (documentation v0.1, 2026-05-27). It predates this',
    'manifest and is kept as evidence, not as the current index.',
    '',
  ].join('\n')
}

const expected = new Map()
for (const h of manifest.harnesses) {
  if (h.existingAdapter) continue
  expected.set(join(RUNTIMES, `${h.id}.md`), stubFor(h))
}
expected.set(join(RUNTIMES, 'README.md'), readmeFor())

// Fail closed on any operator-specific path in a distributed artifact.
for (const [path, text] of expected) {
  if (ABS_PATH.test(text)) {
    console.error(`gen-harness-adapters: absolute machine path in ${path}`)
    process.exit(4)
  }
}

const args = process.argv.slice(2)
const check = args.includes('--check')
const write = args.includes('--write')
if (check === write) {
  console.error('gen-harness-adapters: pass exactly one of --check or --write')
  process.exit(2)
}

let drift = 0
let written = 0
for (const [path, text] of expected) {
  const current = existsSync(path) ? readFileSync(path, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n') : null
  if (current === text) continue
  drift++
  if (write) {
    // Preserve any pre-existing file that is not one of our generated stubs. The one exception
    // is our own earlier README output, which lacked the marker in the first generator version.
    if (current !== null && !current.startsWith(MARKER)) {
      const ourReadme = path.endsWith('README.md') && current.includes('Generated from [`harnesses.json`]')
      if (!ourReadme) {
        console.error(`gen-harness-adapters: refusing to overwrite a non-generated doc: ${path}`)
        process.exit(3)
      }
    }
    writeFileSync(path, text)
    written++
  } else {
    console.log(`DRIFT ${path}`)
  }
}

// The six pre-existing adapter docs must survive untouched.
for (const h of manifest.harnesses.filter((x) => x.existingAdapter)) {
  const p = join(RUNTIMES, `${h.id}.md`)
  if (!existsSync(p)) {
    console.error(`gen-harness-adapters: existing adapter missing: ${p}`)
    process.exit(3)
  }
}

if (check) {
  if (drift) {
    console.error(`gen-harness-adapters: ${drift} generated file(s) out of date; run --write`)
    process.exit(1)
  }
  console.log(`gen-harness-adapters: ${expected.size} generated file(s) byte-identical; ${manifest.harnesses.filter((h) => h.existingAdapter).length} existing docs preserved; 0 writes`)
  process.exit(0)
}
console.log(`gen-harness-adapters: wrote ${written} file(s); ${expected.size - written} already current`)
