// node --test packs/web-excellence/tests/install-agents.test.mjs
// install.sh carries the three web workers into a repo: added when missing,
// left alone when identical, set aside (never deleted) when a local copy
// differs, and skipped on --no-agents, --skills-only, and --dry-run.

import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const PACK = join(dirname(fileURLToPath(import.meta.url)), '..');
const INSTALL = join(PACK, 'install.sh');
const AGENTS = readdirSync(join(PACK, 'agents')).filter((f) => f.endsWith('.md')).sort();

function freshRepo() {
  const dir = mkdtempSync(join(tmpdir(), 'web-excellence-agents-'));
  execFileSync('git', ['init', '-q', dir]);
  return dir;
}

function install(dir, ...flags) {
  return execFileSync('bash', [INSTALL, dir, '--no-db', '--no-ci', ...flags], { encoding: 'utf8' });
}

const read = (p) => readFileSync(p, 'utf8');

test('the pack carries the maker, the judge, and the steward', () => {
  assert.deepEqual(AGENTS, ['worker-visual-qa.md', 'worker-web-builder.md', 'worker-web-steward.md']);
  for (const file of AGENTS) {
    const text = read(join(PACK, 'agents', file));
    const fm = text.match(/^---\n([\s\S]*?)\n---\n/);
    assert.ok(fm, `${file}: frontmatter`);
    assert.match(fm[1], new RegExp(`^name: ${file.replace(/\.md$/, '')}$`, 'm'), `${file}: name matches the file`);
    assert.match(fm[1], /^model: (opus|sonnet|haiku)$/m, `${file}: model tier`);
    const tools = fm[1].match(/^tools: (.*)$/m)?.[1] ?? '';
    assert.ok(tools.includes('Read'), `${file}: tools listed`);
    assert.ok(!/\bAgent\b/.test(tools), `${file}: a worker does not hold the Agent tool`);
    assert.match(text, /GENERATED by scripts\/agent-compile\.mjs/, `${file}: compiled, not hand-written`);
  }
});

test('a fresh install adds every agent byte for byte and ignores the set-aside folder', () => {
  const dir = freshRepo();
  try {
    const out = install(dir);
    for (const file of AGENTS) {
      assert.match(out, new RegExp(`add {4}agent ${file.replace(/\.md$/, '')}`));
      assert.equal(read(join(dir, '.claude/agents', file)), read(join(PACK, 'agents', file)));
    }
    assert.ok(read(join(dir, '.gitignore')).split('\n').includes('.claude/agents.replaced/'));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('a re-run leaves identical agents alone', () => {
  const dir = freshRepo();
  try {
    install(dir);
    const out = install(dir);
    for (const file of AGENTS) assert.match(out, new RegExp(`ok {5}agent ${file.replace(/\.md$/, '')}`));
    assert.ok(!existsSync(join(dir, '.claude/agents.replaced')));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('a local copy that differs is set aside outside .claude/agents, then replaced', () => {
  const dir = freshRepo();
  try {
    install(dir);
    const target = join(dir, '.claude/agents/worker-web-builder.md');
    writeFileSync(target, read(target) + '\nlocal edit\n');
    const out = install(dir);
    assert.match(out, /update agent worker-web-builder/);
    assert.match(read(join(dir, '.claude/agents.replaced/worker-web-builder.md')), /local edit/);
    assert.equal(read(target), read(join(PACK, 'agents/worker-web-builder.md')));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('--no-agents, --skills-only, and --dry-run write no agents', () => {
  for (const flag of ['--no-agents', '--skills-only', '--dry-run']) {
    const dir = freshRepo();
    try {
      install(dir, flag);
      const agentsDir = join(dir, '.claude/agents');
      const written = existsSync(agentsDir) ? readdirSync(agentsDir) : [];
      assert.deepEqual(written, [], `${flag}: no agent files`);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }
});
