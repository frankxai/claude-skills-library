#!/usr/bin/env bash
# sync-agents.sh — re-vendor the web workers from an Agent OS checkout.
#
#   ./sync-agents.sh /path/to/agentic-creator-os           copy them and rewrite the pin
#   ./sync-agents.sh /path/to/agentic-creator-os --check   exit 1 when a vendored copy differs
#
# The agents are compiled in frankxai/agentic-creator-os (agent-os/specs and
# agent-os/roles → .claude/agents) and evaluated there. This pack carries the
# brand-neutral core compile so the maker, the judge and the steward travel
# with the skills they load. Never edit agents/*.md here: change the spec or
# role module in agentic-creator-os, recompile, and re-run this script.
#
# A local checkout rather than a clone, so the pin can be any commit, including
# one on a branch that has not merged yet; the pin records which.
set -euo pipefail

PACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="${1:-}"
CHECK=0
[ "${2:-}" = "--check" ] && CHECK=1

AGENTS="worker-web-builder worker-web-steward worker-visual-qa"

if [ -z "$SRC" ] || [ ! -d "$SRC/.claude/agents" ] || [ ! -d "$SRC/agent-os/specs" ]; then
  echo "usage: sync-agents.sh <path-to-agentic-creator-os> [--check]" >&2
  exit 2
fi

drift=0
for a in $AGENTS; do
  from="$SRC/.claude/agents/$a.md"
  to="$PACK_DIR/agents/$a.md"
  if [ ! -f "$from" ]; then
    echo "!! $a is not compiled in $SRC (.claude/agents/$a.md missing) — run npm run agents:compile there" >&2
    exit 1
  fi
  if [ $CHECK -eq 1 ]; then
    if ! cmp -s "$from" "$to"; then
      echo "drift  $a"
      drift=1
    fi
  else
    mkdir -p "$PACK_DIR/agents"
    cp "$from" "$to"
    echo "synced $a"
  fi
done

if [ $CHECK -eq 1 ]; then
  [ $drift -eq 0 ] && echo "agents in sync with $SRC"
  exit $drift
fi

sha="$(git -C "$SRC" rev-parse HEAD)"
branch="$(git -C "$SRC" rev-parse --abbrev-ref HEAD)"
SOURCES="$PACK_DIR/SOURCES.md"
python3 - "$SOURCES" "$sha" "$branch" "$(date -u +%Y-%m-%d)" "$PACK_DIR/agents" $AGENTS <<'PY'
import re, sys
sources, sha, branch, date, agent_dir, *agents = sys.argv[1:]
rows = []
for a in agents:
    text = open(f"{agent_dir}/{a}.md", encoding="utf-8").read()
    m = re.search(r"Spec version ([0-9]+(?:\.[0-9]+)*)", text)
    rows.append(f"| `{a}` | {m.group(1) if m else '?'} | `{sha[:12]}` ({branch}) | {date} |")
block = "\n".join([
    "<!-- AGENT-PINS:BEGIN — generated by sync-agents.sh, do not hand-edit -->",
    "",
    "| Agent | Spec version | Compiled at agentic-creator-os | Synced |",
    "|---|---|---|---|",
    *rows,
    "",
    "<!-- AGENT-PINS:END -->",
])
text = open(sources, encoding="utf-8").read()
pattern = re.compile(r"<!-- AGENT-PINS:BEGIN.*?<!-- AGENT-PINS:END -->", re.S)
if not pattern.search(text):
    sys.exit("!! SOURCES.md has no AGENT-PINS block to rewrite")
open(sources, "w", encoding="utf-8").write(pattern.sub(lambda _: block, text))
print(f"pinned {len(agents)} agents at {sha[:12]} ({branch})")
PY
